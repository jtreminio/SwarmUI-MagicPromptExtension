async page => {
    const check = (value, message) => { if (!value) throw new Error(message); };
    await page.reload();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.waitForFunction(() => MP.settingsLoaded && document.querySelector('#input_mpdecisionmodelid option[value="typesafe/new"]'));
    const trigger = page.locator('#mp_decision_model_dropdown_trigger');
    const menu = page.locator('#mp_decision_model_dropdown_popover');
    await trigger.click();
    const requestPricedRow = menu.locator('.mp-model-dropdown-row-label').filter({ hasText: 'Parallel: Decision' });
    check(await requestPricedRow.textContent() === 'Parallel: Decision · $0', 'Decision row should show only the input price in the prompt model format');
    await menu.locator('input').fill('typesafe/new');
    await menu.locator('.mp-model-dropdown-row').filter({ hasText: 'New decision' }).click();
    check(await page.locator('#input_mpdecisionmodelid').inputValue() === 'typesafe/new', 'Generate did not select decision model');
    check(await trigger.textContent() === 'TypeSafe: New decision · $0.2', 'Decision trigger should show the selected model with compact input pricing');
    check(await page.evaluate(() => MP.settings.decisions.model === '' && MP.settings.model === 'google/model-a'), 'Generation override changed shared defaults');
    await trigger.click();
    await menu.locator('input').fill('typesafe/new');
    await menu.locator('.mp-model-dropdown-row').filter({ hasText: 'New decision' }).locator('.mp-model-dropdown-star').click();
    await page.waitForFunction(() => testSettings.decisions?.favoritedModels.includes('typesafe/new'));
    await page.keyboard.press('Escape');
    await trigger.click();
    check((await menu.locator('.mp-model-dropdown-row').nth(1).textContent()).includes('New decision'), 'Starred decision not pinned after default option');
    await menu.locator('.mp-model-dropdown-row').filter({ hasText: 'New decision' }).locator('.mp-model-dropdown-remove').click();
    await page.waitForFunction(() => testSettings.decisions.blockedModels.includes('typesafe/new'));
    check(await page.locator('#input_mpdecisionmodelid').inputValue() === 'typesafe/new', 'Blocking silently switched generation model');
    check(await page.evaluate(() => testSettings.favoritedModels.openrouter.join() === 'google/model-a'), 'Decision star changed prompt preferences');
    await page.keyboard.press('Escape');
    await trigger.click();
    check(await menu.locator('.mp-model-dropdown-row').filter({ hasText: 'New decision' }).count() === 0, 'Blocked model still selectable');
    await menu.locator('.mp-model-dropdown-row').filter({ hasText: 'Settings default' }).click();
    check(await page.locator('#input_mpdecisionmodelid').inputValue() === '', 'Could not return to Settings default');
    await page.evaluate(() => {
        const original = document.getElementById('input_mpdecisionmodelid');
        original.replaceWith(original.cloneNode(true));
        postParamBuildSteps.forEach(step => step());
    });
    await page.waitForFunction(() => document.getElementById('mp_decision_model_dropdown_trigger')?.previousElementSibling === document.getElementById('input_mpdecisionmodelid'));
    check(await page.locator('#mp_decision_model_dropdown_trigger').count() === 1, 'Parameter rebuild duplicated decision trigger');
    await trigger.click();
    await menu.locator('.mp-model-dropdown-row').filter({ hasText: 'Older decision' }).click();
    check(await page.locator('#input_mpdecisionmodelid').inputValue() === 'typesafe/old', 'Rebuilt decision dropdown is not functional');
    await page.evaluate(() => {
        window.gen_param_types = [{ id: 'mpdecisionmodelid', values: [''], value_names: ['Settings default'] }];
        document.body.insertAdjacentHTML('beforeend', '<select id="preset_input_mpdecisionmodelid"></select>');
        mpRefreshDecisionModelControls();
        document.getElementById('preset_input_mpdecisionmodelid').value = 'parallel/decision';
        triggerChangeFor(document.getElementById('preset_input_mpdecisionmodelid'));
    });
    await page.evaluate(() => { gen_param_types[0].value_names[0] = 'Settings default'; });
    await page.evaluate(() => new Promise(resolve => refreshParameterValues(true, null, resolve)));
    check(await page.locator('#input_mpdecisionmodelid').inputValue() === 'typesafe/old', 'Refresh lost Generate model override');
    check(await page.locator('#preset_input_mpdecisionmodelid').inputValue() === 'parallel/decision', 'Refresh overwrote independent preset model');
    check(await page.locator('#preset_input_mpdecisionmodelid option:checked').textContent() === 'Parallel: Decision · $0', 'Preset decision model should use the same input price label');
    await page.evaluate(() => setDirectParamValue(gen_param_types[0], 'missing/old-judge', document.getElementById('preset_input_mpdecisionmodelid')));
    await page.evaluate(() => new Promise(resolve => refreshParameterValues(true, null, resolve)));
    check(await page.locator('#preset_input_mpdecisionmodelid').inputValue() === 'missing/old-judge', 'Refresh lost stale preset model');
    check((await page.locator('#preset_input_mpdecisionmodelid option:checked').textContent()).includes('unavailable'), 'Stale preset model has no warning');
    check((await page.locator('#input_mpdecisionmodelid option[value=""]').textContent()).includes('not selected'), 'Native refresh lost the default configuration label');
    await page.evaluate(() => testDecisionModels.push({ model: 'typesafe/refreshed', name: 'Refreshed decision', created: 99, decisionModel: true, costIn: '$0.1' }));
    await page.evaluate(() => new Promise(resolve => refreshParameterValues(true, null, resolve)));
    await page.waitForFunction(() => document.querySelector('#input_mpdecisionmodelid option[value="typesafe/refreshed"]'), null, { timeout: 5000 });
    return 'Generate decision models: selection, default fallback, independent stars/blocks, parameter rebuild passed';
}
