async page => {
  const check = (value, message) => { if (!value) throw new Error(message); };
  await page.reload();
  await page.setViewportSize({width:1440,height:1000});
  await page.waitForFunction(() => MP.settingsLoaded && document.querySelector('#input_mpmodelid').options.length > 2);
  await page.locator('#magicprompt_sidebar_settings_link button').click();
  await page.getByRole('tab', { name: 'Models', exact: true }).click();
  await page.locator('#modelSelect').click();
  const native = page.locator('#popover_uiimprover_modelSelect');
  await native.waitFor();
  check(await page.locator('[id^="popover_uiimprover_"]').count() === 1, 'Default model must open exactly one native Swarm dropdown');
  check(await page.locator('.select2').count() === 0, 'Settings must not use Select2');
  await native.locator('input').fill('local/model-b');
  await native.locator('.sui_popover_model_button').filter({hasText:'Local model'}).click();
  check(await page.locator('#modelSelect').inputValue() === 'local/model-b', 'Default model selection failed');
  await page.locator('#modelSelect').click();
  await native.locator('input').waitFor();
  await page.keyboard.press('Escape');
  check(await native.count() === 0 && await page.locator('#settingsModal.show').count() === 1, 'Escape should close only the native dropdown');
  let color;
  for (const id of ['mpFavoriteModels', 'mpBlockedModels']) {
    const trigger = page.locator(`#${id}Trigger`);
    const panel = page.locator(`#${id}Panel`);
    await trigger.focus();
    await page.keyboard.press('Enter');
    await panel.waitFor();
    check(await page.locator('.mp-model-panel:visible').count() === 1, 'More than one checkbox picker open');
    check(await page.locator('[id^="popover_uiimprover_"]').count() === 0, 'Preference picker also opened a native dropdown');
    const background = await panel.evaluate(el => getComputedStyle(el).backgroundColor);
    if (color) check(color === background, 'Favorites and blocked backgrounds differ');
    color = background;
    await panel.locator('input[type=search]').fill('provider/model-99');
    const box = panel.getByRole('checkbox', {name:/Provider: Model 99/});
    await box.focus();
    await page.keyboard.press('Space');
    check(await box.isChecked(), 'Keyboard checkbox selection failed');
    check(await box.evaluate(el => el === document.activeElement), 'Checkbox lost focus when toggled');
    check(await panel.isVisible(), 'Picker closed during selection');
    check(await panel.locator('input[type=search]').inputValue() === 'provider/model-99', 'Search lost after selection');
    check(await panel.locator('.mp-model-count').textContent() === '2 selected', 'Selected count wrong');
    await panel.locator('input[type=search]').fill('no-such-model');
    check(await panel.getByText('No matching models.').isVisible(), 'Empty search missing');
    await page.keyboard.press('Escape');
    check(!await panel.isVisible() && await page.locator('#settingsModal.show').count() === 1, 'Escape closed settings');
    await trigger.getByRole('button', {name:/Remove Provider: Model 99/}).click();
    check(!await panel.isVisible(), 'Removing chip opened picker');
    await trigger.click();
    await panel.getByRole('button',{name:'Clear',exact:true}).click();
    check(await panel.locator('.mp-model-count').textContent() === '0 selected', 'Clear failed');
    await page.locator('#mpSettingsTitle').click();
    check(!await panel.isVisible(), 'Outside click did not close picker');
  }
  await page.getByRole('button', {name:'Cancel',exact:true}).click();
  await page.waitForFunction(() => document.querySelectorAll('.modal-backdrop').length === 0);
  check(await page.evaluate(() => testSettings.favoritedModels.openrouter[0] === 'google/model-a' && testSettings.blockedModels.openrouter[0] === 'old/model'), 'Canceled preferences persisted');
  await page.locator('#magicprompt_sidebar_settings_link button').click();
  await page.getByRole('tab', {name:'Models',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.locator('#mpBlockedModelsTrigger').click();
  const bounds = await page.locator('#mpBlockedModelsPanel').boundingBox();
  check(bounds.x >= 0 && bounds.x + bounds.width <= 390 && bounds.y >= 0 && bounds.y + bounds.height <= 844, 'Mobile picker outside viewport');
  await page.locator('#mpBlockedModelsPanel input[type=search]').fill('local/model-b');
  await page.locator('#mpBlockedModelsPanel').getByRole('checkbox',{name:/Local model/}).check();
  await page.locator('#mpBlockedModelsPanel input[type=search]').fill('google/model-a');
  await page.locator('#mpBlockedModelsPanel').getByRole('checkbox',{name:/Google: Fast model/}).check();
  check(await page.locator('#modelSelect').inputValue() === '', 'Blocking the current default did not clear it');
  check(await page.locator('#modelSelect option[value="google/model-a"]').count() === 0, 'Blocked default remains in its dropdown');
  check(await page.locator('#mpFavoriteModelsPanel input[value="google/model-a"]').count() === 0, 'Blocked favorite remains in its dropdown');
  check(await page.locator('#mpFavoriteModelsTrigger [data-remove-model="google/model-a"]').count() === 0, 'Blocked favorite chip remains');
  await page.keyboard.press('Escape');
  await page.getByRole('button', {name:'Save and close',exact:true}).click();
  await page.waitForFunction(() => document.querySelectorAll('.modal-backdrop').length === 0);
  check(await page.evaluate(() => testSettings.blockedModels.openrouter.includes('local/model-b')), 'Checkbox preference not saved');
  check(await page.evaluate(() => testSettings.model === '' && !testSettings.favoritedModels.openrouter.includes('google/model-a')), 'Blocked default/favorite remained in saved settings');
  return {passed:true, checks:'native default dropdown; checkbox search, keyboard focus, chips, count, Clear, matching backgrounds, Escape, outside click, cancel/save, mobile placement'};
}
