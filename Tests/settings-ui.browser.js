async page => {
  const check = (value, message) => { if (!value) throw new Error(message); };
  await page.reload();
  await page.evaluate(() => localStorage.removeItem('magicprompt_prompt_history'));
  await page.waitForFunction(() => MP.settingsLoaded && document.querySelector('#mp_model_dropdown_trigger'));
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#magicprompt_sidebar_settings_link button').click();
  await page.locator('#settingsModal.show').waitFor();
  await page.getByRole('tab',{name:'Instructions',exact:true}).click();
  await page.getByRole('button',{name:'New instruction',exact:true}).click();
  await page.locator('#mpInstructionTitle').fill('Browser regression');
  await page.locator('#mpInstructionContent').fill('Preserve this exact custom instruction.');
  check(await page.locator('.modal-backdrop').count() === 1,'Instruction editor added a backdrop');
  await page.getByRole('tab',{name:'Models',exact:true}).click();
  await page.locator('#mpBlockedModelsTrigger').click();
  await page.locator('#mpBlockedModelsPanel .mp-model-filter').fill('local/model-b');
  await page.locator('#mpBlockedModelsPanel').getByRole('checkbox',{name:/Local model/}).check();
  await page.keyboard.press('Escape');
  check(await page.locator('#settingsModal').evaluate(el=>el.classList.contains('show')),'Escape in dropdown closed settings');
  check(await page.locator('#mpBlockedModels').evaluate(el=>[...el.selectedOptions].some(o=>o.value==='local/model-b')),'Model search did not select block');
  await page.locator('#mpFavoriteModelsTrigger').click();
  await page.locator('#mpFavoriteModelsPanel .mp-model-filter').fill('local/model-b');
  check(await page.locator('#mpFavoriteModelsPanel').getByRole('checkbox',{name:/Local model/}).count()===0,'Blocked model present in favorites');
  check(await page.locator('#modelSelect option[value="local/model-b"]').count()===0,'Blocked model present in defaults');
  await page.keyboard.press('Escape');
  await page.locator('#mpBlockedModelsTrigger').click();
  await page.locator('#mpBlockedModelsPanel').getByRole('checkbox',{name:/Local model/}).uncheck();
  await page.keyboard.press('Escape');
  await page.locator('#mpFavoriteModelsTrigger').click();
  await page.locator('#mpFavoriteModelsPanel').getByRole('checkbox',{name:/Local model/}).check();
  await page.keyboard.press('Escape');
  check(!await page.locator('#mpBlockedModels').evaluate(el=>[...el.selectedOptions].some(o=>o.value==='local/model-b')),'Unblocking failed');
  await page.evaluate(()=>window.failSave=true);
  await page.getByRole('button',{name:'Save and close',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Simulated save failure'}).waitFor();
  check(await page.locator('#settingsModal').isVisible(),'Failed save closed modal');
  await page.evaluate(()=>window.failSave=false);
  await page.getByRole('button',{name:'Save and close',exact:true}).click();
  await page.locator('#settingsModal').waitFor({state:'hidden'});
  await page.waitForFunction(()=>document.querySelectorAll('.modal-backdrop').length===0);
  check(await page.locator('.modal-backdrop').count()===0,'Backdrop remained after save');
  check(await page.evaluate(()=>Object.values(testSettings.instructions.custom).some(i=>i.title==='Browser regression'&&i.content==='Preserve this exact custom instruction.')),'Instruction not persisted');
  for(let i=0;i<3;i++){
    await page.locator('#magicprompt_sidebar_settings_link button').click();
    await page.getByRole('tab',{name:'Instructions',exact:true}).click();
    await page.getByRole('button',{name:'Browser regression',exact:true}).click();
    await page.locator('#mpInstructionContent').fill('Discard this change');
    await page.getByRole('button',{name:'Cancel',exact:true}).click();
    await page.locator('#settingsModal').waitFor({state:'hidden'});
  await page.waitForFunction(()=>document.querySelectorAll('.modal-backdrop').length===0);
    check(await page.locator('.modal-backdrop').count()===0,'Backdrop leaked on reopen');
  }
  check(await page.evaluate(()=>Object.values(testSettings.instructions.custom).some(i=>i.content==='Preserve this exact custom instruction.')),'Cancel saved changes');
  await page.evaluate(()=>{MP.PromptHistory.record('<wc:first>');MP.PromptHistory.record('Second prompt');});
  await page.locator('#magicprompt_sidebar_history_link button').click();
  await page.locator('#promptHistoryFilter').fill('second');
  await page.getByRole('button',{name:'Append',exact:true}).click();
  await page.locator('#promptHistoryModal').waitFor({state:'hidden'});
  await page.waitForFunction(()=>document.querySelectorAll('.modal-backdrop').length===0);
  check(await page.locator('#alt_prompt_textbox').inputValue()==='Current prompt Second prompt','Append failed');
  check(await page.locator('#input_prompt').inputValue()==='Current prompt Second prompt','Hidden prompt out of sync');
  await page.locator('#magicprompt_sidebar_history_link button').click();
  await page.locator('#promptHistoryFilter').fill('first');
  await page.getByRole('button',{name:'Use',exact:true}).focus();
  await page.keyboard.press('Enter');
  await page.locator('#promptHistoryModal').waitFor({state:'hidden'});
  await page.waitForFunction(()=>document.querySelectorAll('.modal-backdrop').length===0);
  check(await page.locator('#alt_prompt_textbox').inputValue()==='<wc:first>','Keyboard Use failed');
  await page.locator('#magicprompt_sidebar_history_link button').click();
  await page.getByRole('button',{name:'Delete',exact:true}).first().focus();
  await page.keyboard.press('Space');
  check(await page.locator('.mp-history-item').count()===1,'Keyboard delete fired twice');
  await page.getByRole('button',{name:'Copy',exact:true}).click();
  await page.getByRole('button',{name:'Copied',exact:true}).waitFor();
  await page.getByRole('button',{name:'Clear All',exact:true}).click();
  check(await page.locator('.mp-history-item').count()===1,'First clear click deleted history');
  await page.getByRole('button',{name:'Click again to confirm',exact:true}).click();
  check(await page.locator('.mp-history-item').count()===0,'Clear confirmation failed');
  await page.getByRole('button',{name:'Close',exact:true}).last().click();
  await page.locator('#promptHistoryModal').waitFor({state:'hidden'});
  await page.waitForFunction(()=>document.querySelectorAll('.modal-backdrop').length===0);
  await page.locator('#magicprompt_sidebar_settings_link button').click();
  await page.getByRole('tab',{name:'Instructions',exact:true}).click();
  await page.getByRole('button',{name:'Browser regression',exact:true}).click();

  await page.setViewportSize({width:390,height:844});
  check(await page.locator('#settingsModal').evaluate(el=>el.scrollWidth<=window.innerWidth),'Mobile horizontal overflow');

  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.locator('#settingsModal').waitFor({state:'hidden'});
  await page.waitForFunction(()=>document.querySelectorAll('.modal-backdrop').length===0);
  check(await page.locator('.modal-backdrop').count()===0,'Final backdrop leak');
  check(await page.evaluate(() => testErrors.length === 0), 'Unexpected UI errors');
  return {passed:true,checks:'instruction create/edit/cancel, searched preferences, exclusivity, failed save/retry, repeated reopen, history use/append/copy/delete/clear, keyboard, mobile'};
}
