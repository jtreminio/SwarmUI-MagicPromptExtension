async page => {
  const check = (value, message) => { if (!value) throw new Error(message); };
  await page.reload();
  await page.waitForFunction(() => MP.settingsLoaded);
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#magicprompt_sidebar_settings_link button').click();
  await page.locator('#mpBackend').selectOption('openaiapi');
  await page.locator('#mpBaseUrl').fill('http://localhost:5678');
  await page.locator('#mpTimeout').fill('45');
  await page.getByRole('tab',{name:'Models',exact:true}).click();
  await page.locator('#mpRefreshModels').click();
  await page.getByRole('status').filter({hasText:'103 models available.'}).waitFor();
  await page.locator('#modelSelect').click();
  await page.locator('#popover_uiimprover_modelSelect input').fill('Local model');
  await page.locator('#popover_uiimprover_modelSelect .sui_popover_model_button').filter({hasText:'Local model'}).click();
  await page.getByRole('button',{name:'Save and close',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.modal-backdrop').length===0);
  check(await page.evaluate(()=>testSettings.backend==='openaiapi'&&testSettings.backends.openaiapi.timeout===45&&testSettings.backends.openaiapi.baseurl==='http://localhost:5678'),'Local connection not saved');
  check(await page.locator('#input_mpmodelid').inputValue()==='local/model-b','Old provider model retained');
  await page.locator('#magicprompt_sidebar_settings_link button').click();
  await page.getByRole('tab',{name:'Instructions',exact:true}).click();
  await page.locator('#mpImportFile').setInputFiles('Tests/instructions.fixture.json');
  await page.getByRole('button',{name:'Imported instruction',exact:true}).click();
  check(await page.locator('#mpInstructionContent').inputValue()==='Keep imported content','Import failed');
  check(await page.getByRole('button',{name:'Cinematic 1',exact:true}).count()===1,'Import overwrote existing ID');
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export',exact:true}).click();
  check((await downloadPromise).suggestedFilename()==='magicprompt-instructions.json','Export failed');
  await page.locator('summary').click();
  await page.locator('#mpInstructionBrief').fill('Create cinematic prompts');
  await page.getByRole('button',{name:'Generate draft',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Draft generated'}).waitFor();
  check(await page.locator('#mpInstructionContent').inputValue()==='You create cinematic prompts with precise composition.','AI draft failed');
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.modal-backdrop').length===0);
  check(await page.evaluate(()=>!Object.values(testSettings.instructions.custom).some(i=>i.title==='Imported instruction')),'Import persisted on cancel');
  await page.evaluate(async()=>{await showSettingsModal();closeSettingsModal();});
  await page.waitForFunction(()=>document.querySelectorAll('.modal-backdrop').length===0);
  return {passed:true,checks:'local URL/timeout/model, provider switch, import collision, export, AI draft, discard import, immediate close'};
}
